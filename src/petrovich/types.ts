/**
 * Общие типы для интеграции с Петровичем.
 */

export type SortMode = 'popular' | 'cheap';

export type Product = {
	/** Название товара (человекочитаемое). */
	name: string;
	/** Цена в виде строки для вывода пользователю (может содержать "было ..."). */
	price: string;
	/** Наличие/доступность (как на сайте, если распознали). */
	availability: string;
	/** Ссылка на товар. */
	url: string;
};

